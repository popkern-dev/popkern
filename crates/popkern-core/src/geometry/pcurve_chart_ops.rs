//! Chart-metric operations on pcurves: re-anchoring and rescaling
//! stored UV coordinates when the OWNING CHART's frame or metric
//! changes (rigid rotation re-anchors rotational-chart U; a uniform
//! body scale stretches cylinder/cone V and plane UV).
//!
//! Extracted from `pcurve.rs` to stay under the 500-line structural
//! cap.

use super::{Pcurve, PcurveGeometry};

impl Pcurve {
    /// Shift the U coordinate of the whole pcurve by a constant.
    ///
    /// Rotational charts (cylinder/cone/sphere/torus) anchor U to
    /// `orthonormal_basis(axis)`, a convention of the AXIS DIRECTION
    /// rather than of the material: a rigid rotation of the body
    /// changes the anchor, offsetting every stored U by one constant
    /// angle. `BRep::transform` uses this to re-anchor pcurves.
    pub fn shift_u(&mut self, delta: f64) {
        match &mut self.geometry {
            PcurveGeometry::Linear { start, end } => {
                start.0 += delta;
                end.0 += delta;
            }
            PcurveGeometry::Elliptical { center, .. } => {
                center.0 += delta;
            }
            PcurveGeometry::Sinusoidal { u_offset, .. } => {
                *u_offset += delta;
            }
            PcurveGeometry::Nurbs(c) => {
                for cp in &mut c.control_points {
                    cp.x += delta;
                }
            }
            PcurveGeometry::CylinderArcViaRationalQuad {
                theta_a, theta_b, ..
            } => {
                *theta_a += delta;
                *theta_b += delta;
            }
        }
    }

    /// Scale the V coordinate of the whole pcurve by a constant.
    ///
    /// Cylinder and cone charts measure V as arc length along a UNIT
    /// axis, so a uniform body scale `s` stretches every stored V by
    /// `s` while U (an angle) is invariant. `BRep::transform` uses
    /// this to keep pcurves exact under similarity transforms with
    /// `s ≠ 1`.
    ///
    /// Returns `false` when the pcurve form cannot represent the
    /// scaled curve exactly (an [`PcurveGeometry::Elliptical`] whose
    /// `rotation` is not a multiple of π/2 — an anisotropic scale of
    /// a rotated ellipse leaves that parameterization family). The
    /// pcurve is untouched in that case and the caller must decline.
    #[must_use]
    pub fn scale_v(&mut self, s: f64) -> bool {
        match &mut self.geometry {
            PcurveGeometry::Linear { start, end } => {
                start.1 *= s;
                end.1 *= s;
            }
            PcurveGeometry::Elliptical {
                center,
                u_radius,
                v_radius,
                rotation,
                ..
            } => {
                let quarter_turns = *rotation / std::f64::consts::FRAC_PI_2;
                let nearest = quarter_turns.round();
                if (quarter_turns - nearest).abs() > 1.0e-9 {
                    return false;
                }
                center.1 *= s;
                // Odd quarter turns put the major axis along V, so
                // the V stretch lands on `u_radius`.
                if (nearest as i64).rem_euclid(2) == 0 {
                    *v_radius *= s;
                } else {
                    *u_radius *= s;
                }
            }
            PcurveGeometry::Sinusoidal {
                v_const,
                v_cos,
                v_sin,
                ..
            } => {
                *v_const *= s;
                *v_cos *= s;
                *v_sin *= s;
            }
            PcurveGeometry::Nurbs(c) => {
                for cp in &mut c.control_points {
                    cp.y *= s;
                }
            }
            PcurveGeometry::CylinderArcViaRationalQuad { v_const, .. } => {
                *v_const *= s;
            }
        }
        true
    }

    /// Scale BOTH UV coordinates of the whole pcurve by a constant.
    ///
    /// Plane charts with unit axes measure U and V as lengths, so a
    /// uniform body scale `s` stretches the whole chart isotropically.
    /// `BRep::transform` uses this to keep inner-loop planar pcurves
    /// exact under similarity transforms with `s ≠ 1` (outer loops
    /// are regenerated by `attach_planar_pcurves`, inner loops are
    /// not).
    ///
    /// Returns `false` when the form cannot represent the scaled
    /// curve exactly ([`PcurveGeometry::Sinusoidal`], whose linear-U
    /// coefficient is pinned to 1 — a cylinder-chart form that does
    /// not occur on planes). The pcurve is untouched in that case.
    #[must_use]
    pub fn scale_uv(&mut self, s: f64) -> bool {
        match &mut self.geometry {
            PcurveGeometry::Linear { start, end } => {
                start.0 *= s;
                start.1 *= s;
                end.0 *= s;
                end.1 *= s;
            }
            PcurveGeometry::Elliptical {
                center,
                u_radius,
                v_radius,
                ..
            } => {
                center.0 *= s;
                center.1 *= s;
                *u_radius *= s;
                *v_radius *= s;
            }
            PcurveGeometry::Sinusoidal { .. } => return false,
            PcurveGeometry::Nurbs(c) => {
                for cp in &mut c.control_points {
                    cp.x *= s;
                    cp.y *= s;
                }
            }
            PcurveGeometry::CylinderArcViaRationalQuad { .. } => return false,
        }
        true
    }
}
