//! Authority facts for shared BRep repair knowledge.

use crate::topology::brep_curve_trim_reconstruction::{
    BrepCurveTrimReconstructionOptions, ExistingTrimStatus, existing_trim_status,
};
use crate::topology::brep_repair_knowledge_fact_record::authority_fact;
use crate::topology::{
    BRep, BrepDegenerateEdgeFinding, BrepDegenerateEdgeKind, BrepRepairFact, BrepRepairFactKind,
    BrepRepairFactState, BrepRepairTopologyHandle, BrepTrimEndpointAgreementFacts,
    BrepTrimEndpointAgreementStatus, CanonicalForm, FaceHandle, HalfEdgeHandle,
    LocalToleranceEvidence, LocalToleranceSource, SurfaceBoundaryHintDeclineReason,
};

/// Typed authority evidence attached to authority facts.
#[derive(Debug, Clone, PartialEq)]
pub struct BrepRepairAuthorityFact {
    /// Authority classification.
    pub kind: BrepRepairAuthorityKind,
    /// Why this authority classification was chosen.
    pub reason: BrepRepairAuthorityReason,
}

/// Which source is currently authoritative or blocking.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum BrepRepairAuthorityKind {
    /// The 3D edge curve is authoritative.
    AuthoritativeEdgeCurve,
    /// A canonical surface boundary is authoritative.
    AuthoritativeSurfaceBoundary,
    /// The trim endpoint evidence is authoritative.
    AuthoritativeTrimEndpoint,
    /// An explicit degenerate topology contract is authoritative.
    AuthoritativeDegenerateTopology,
    /// A generated construction record is authoritative.
    GeneratedConstructionRecord,
    /// Imported trim evidence exists but should not be trusted without validation.
    ImportedUntrustedTrim,
    /// A pcurve is stale relative to its dependencies.
    StalePcurve,
    /// Side-local surfaces or trims disagree.
    SideLocalSurfaceMismatch,
    /// No authoritative source exists for this local relation.
    NoAuthoritativeSource,
}

/// Machine-readable reason for an authority classification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum BrepRepairAuthorityReason {
    /// Edge data declares 3D canonical authority and an edge curve exists.
    EdgeCanonical3D,
    /// Edge data declares parametric canonical authority and trims agree.
    EdgeCanonicalParametric,
    /// Analytic pcurve was generated by local construction code.
    GeneratedAnalyticPcurve,
    /// NURBS pcurve requires validation before it can be trusted.
    NurbsTrimRequiresValidation,
    /// Direct trim endpoint order agrees within local tolerance.
    TrimEndpointAcceptedDirect,
    /// Reconciled trim endpoint order agrees within local tolerance.
    TrimEndpointAcceptedReconciled,
    /// Canonical surface-boundary evidence exists for this side.
    SurfaceBoundaryAvailable,
    /// No canonical surface-boundary evidence exists for this side.
    MissingSurfaceBoundaryEvidence,
    /// Authored surface-boundary evidence disagrees with committed trim evidence.
    SurfaceBoundaryTrimDisagreement,
    /// The half-edge has no pcurve.
    MissingPcurve,
    /// The half-edge pcurve exists but does not validate against local dependencies.
    StalePcurve,
    /// Owning surface is missing.
    MissingSurface,
    /// Required topology is missing.
    MissingTopology,
    /// Evaluation failed numerically.
    EvaluationFailed,
    /// Opposite sides disagree beyond tolerance.
    SideDisagreement,
    /// A degenerate edge is valid because its surface-trim image is collapsed.
    DegenerateCollapsedSurfaceTrim,
    /// A degenerate edge has no authoritative trim/surface evidence.
    DegenerateZeroLengthVertexEdge,
    /// A degenerate edge has conflicting or non-collapsed trim evidence.
    DegenerateAmbiguousCollapsedTrim,
}

pub(super) fn surface_boundary_authority_fact(
    id: usize,
    brep: &BRep,
    face: FaceHandle,
    half_edge: HalfEdgeHandle,
) -> BrepRepairFact {
    let (state, authority) = surface_boundary_authority(brep, half_edge);
    let mut handles = vec![
        BrepRepairTopologyHandle::Face(face),
        BrepRepairTopologyHandle::HalfEdge(half_edge),
    ];
    if let Some(edge) = brep.half_edges.get(half_edge).map(|data| data.edge) {
        handles.push(BrepRepairTopologyHandle::Edge(edge));
    }
    authority_fact(
        id,
        BrepRepairFactKind::Authority,
        state,
        handles,
        Some(format!(
            "authority {face:?}@{half_edge:?} kind={:?} reason={:?}",
            authority.kind, authority.reason
        )),
        None,
        Some(authority),
    )
}

fn surface_boundary_authority(
    brep: &BRep,
    half_edge: HalfEdgeHandle,
) -> (BrepRepairFactState, BrepRepairAuthorityFact) {
    if brep.surface_boundary_hint(half_edge).is_some() {
        return (
            BrepRepairFactState::Derived,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::AuthoritativeSurfaceBoundary,
                reason: BrepRepairAuthorityReason::SurfaceBoundaryAvailable,
            },
        );
    }
    let Some(decline) = brep.surface_boundary_decline(half_edge) else {
        return (
            BrepRepairFactState::Unavailable,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
                reason: BrepRepairAuthorityReason::MissingSurfaceBoundaryEvidence,
            },
        );
    };
    match decline.reason {
        SurfaceBoundaryHintDeclineReason::MissingPcurve => (
            BrepRepairFactState::Unavailable,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
                reason: BrepRepairAuthorityReason::MissingPcurve,
            },
        ),
        SurfaceBoundaryHintDeclineReason::NotOnCanonicalBoundary => (
            BrepRepairFactState::Unavailable,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
                reason: BrepRepairAuthorityReason::MissingSurfaceBoundaryEvidence,
            },
        ),
        SurfaceBoundaryHintDeclineReason::AuthoredHintBoundaryMismatch
        | SurfaceBoundaryHintDeclineReason::AuthoredHintEndpointMismatch => (
            BrepRepairFactState::Contradictory,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::SideLocalSurfaceMismatch,
                reason: BrepRepairAuthorityReason::SurfaceBoundaryTrimDisagreement,
            },
        ),
    }
}

pub(super) fn trim_authority_facts(
    start_id: usize,
    brep: &BRep,
    agreement: &BrepTrimEndpointAgreementFacts,
    state: BrepRepairFactState,
    tolerance: f64,
    tolerance_source: LocalToleranceSource,
    samples: usize,
) -> Vec<BrepRepairFact> {
    let trim_authority = trim_authority(agreement);
    let tolerance = agreement
        .selected_disagreement
        .is_finite()
        .then_some(LocalToleranceEvidence {
            tolerance,
            residual: agreement.selected_disagreement,
            source: tolerance_source,
        });
    let mut facts = Vec::new();
    for half_edge in [agreement.half_edge, agreement.adjacent_half_edge] {
        push_authority_fact(
            &mut facts,
            start_id,
            brep,
            half_edge,
            state,
            tolerance.clone(),
            agreement.status,
            trim_authority.clone(),
        );
        if let Some(source_authority) = trim_source_authority(brep, half_edge) {
            push_authority_fact(
                &mut facts,
                start_id,
                brep,
                half_edge,
                BrepRepairFactState::Observed,
                tolerance.clone(),
                agreement.status,
                source_authority,
            );
        }
        if let Some(stale_authority) = stale_pcurve_authority(brep, half_edge, tolerance, samples) {
            push_authority_fact(
                &mut facts,
                start_id,
                brep,
                half_edge,
                BrepRepairFactState::Stale,
                tolerance.clone(),
                agreement.status,
                stale_authority,
            );
        }
        if let Some(edge_authority) = edge_curve_authority(brep, half_edge) {
            push_authority_fact(
                &mut facts,
                start_id,
                brep,
                half_edge,
                BrepRepairFactState::Derived,
                tolerance.clone(),
                agreement.status,
                edge_authority,
            );
        }
    }
    facts
}

fn trim_source_authority(
    brep: &BRep,
    half_edge: HalfEdgeHandle,
) -> Option<BrepRepairAuthorityFact> {
    let pcurve = brep.half_edges.get(half_edge)?.pcurve.as_ref()?;
    if pcurve.is_analytic() {
        Some(BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::GeneratedConstructionRecord,
            reason: BrepRepairAuthorityReason::GeneratedAnalyticPcurve,
        })
    } else {
        Some(BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::ImportedUntrustedTrim,
            reason: BrepRepairAuthorityReason::NurbsTrimRequiresValidation,
        })
    }
}

pub(super) fn degenerate_edge_authority_fact(
    id: usize,
    finding: &BrepDegenerateEdgeFinding,
    tolerance: f64,
    tolerance_source: LocalToleranceSource,
) -> BrepRepairFact {
    let (state, authority) = degenerate_edge_authority(finding);
    authority_fact(
        id,
        BrepRepairFactKind::Authority,
        state,
        vec![BrepRepairTopologyHandle::Edge(finding.edge)],
        Some(format!(
            "authority {:?} kind={:?} reason={:?} degenerate_kind={:?}",
            finding.edge, authority.kind, authority.reason, finding.kind
        )),
        Some(LocalToleranceEvidence {
            tolerance,
            residual: finding.endpoint_gap.max(finding.surface_span),
            source: tolerance_source,
        }),
        Some(authority),
    )
}

fn degenerate_edge_authority(
    finding: &BrepDegenerateEdgeFinding,
) -> (BrepRepairFactState, BrepRepairAuthorityFact) {
    match finding.kind {
        BrepDegenerateEdgeKind::CollapsedSurfaceTrim => (
            BrepRepairFactState::Derived,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::AuthoritativeDegenerateTopology,
                reason: BrepRepairAuthorityReason::DegenerateCollapsedSurfaceTrim,
            },
        ),
        BrepDegenerateEdgeKind::ZeroLengthVertexEdge => (
            BrepRepairFactState::Unavailable,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
                reason: BrepRepairAuthorityReason::DegenerateZeroLengthVertexEdge,
            },
        ),
        BrepDegenerateEdgeKind::AmbiguousCollapsedTrim => (
            BrepRepairFactState::Contradictory,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::SideLocalSurfaceMismatch,
                reason: BrepRepairAuthorityReason::DegenerateAmbiguousCollapsedTrim,
            },
        ),
        BrepDegenerateEdgeKind::MissingTopology => (
            BrepRepairFactState::Unavailable,
            BrepRepairAuthorityFact {
                kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
                reason: BrepRepairAuthorityReason::MissingTopology,
            },
        ),
    }
}

fn push_authority_fact(
    facts: &mut Vec<BrepRepairFact>,
    start_id: usize,
    brep: &BRep,
    half_edge: HalfEdgeHandle,
    state: BrepRepairFactState,
    tolerance: Option<LocalToleranceEvidence>,
    trim_status: BrepTrimEndpointAgreementStatus,
    authority: BrepRepairAuthorityFact,
) {
    let mut handles = vec![BrepRepairTopologyHandle::HalfEdge(half_edge)];
    if let Some(edge) = brep.half_edges.get(half_edge).map(|data| data.edge) {
        handles.push(BrepRepairTopologyHandle::Edge(edge));
    }
    facts.push(authority_fact(
        start_id + facts.len(),
        BrepRepairFactKind::Authority,
        state,
        handles,
        Some(format!(
            "authority {:?} kind={:?} reason={:?} trim_status={:?}",
            half_edge, authority.kind, authority.reason, trim_status
        )),
        tolerance,
        Some(authority),
    ));
}

fn trim_authority(agreement: &BrepTrimEndpointAgreementFacts) -> BrepRepairAuthorityFact {
    match agreement.status {
        BrepTrimEndpointAgreementStatus::AcceptedDirect => BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::AuthoritativeTrimEndpoint,
            reason: BrepRepairAuthorityReason::TrimEndpointAcceptedDirect,
        },
        BrepTrimEndpointAgreementStatus::AcceptedReconciled => BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::AuthoritativeTrimEndpoint,
            reason: BrepRepairAuthorityReason::TrimEndpointAcceptedReconciled,
        },
        BrepTrimEndpointAgreementStatus::SideDisagreement => BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::SideLocalSurfaceMismatch,
            reason: BrepRepairAuthorityReason::SideDisagreement,
        },
        BrepTrimEndpointAgreementStatus::MissingPcurve => BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
            reason: BrepRepairAuthorityReason::MissingPcurve,
        },
        BrepTrimEndpointAgreementStatus::MissingSurface => BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
            reason: BrepRepairAuthorityReason::MissingSurface,
        },
        BrepTrimEndpointAgreementStatus::MissingTopology => BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
            reason: BrepRepairAuthorityReason::MissingTopology,
        },
        BrepTrimEndpointAgreementStatus::EvaluationFailed => BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::NoAuthoritativeSource,
            reason: BrepRepairAuthorityReason::EvaluationFailed,
        },
    }
}

fn stale_pcurve_authority(
    brep: &BRep,
    half_edge: HalfEdgeHandle,
    tolerance: Option<LocalToleranceEvidence>,
    samples: usize,
) -> Option<BrepRepairAuthorityFact> {
    let half_edge_data = brep.half_edges.get(half_edge)?;
    half_edge_data.pcurve.as_ref()?;
    let tolerance = tolerance.map_or_else(|| brep.tolerance.linear(), |e| e.tolerance);
    let status = existing_trim_status(
        brep,
        half_edge,
        BrepCurveTrimReconstructionOptions {
            tolerance,
            samples,
            replace_existing: false,
            replace_stale_existing: false,
            expand_bounded_surface_domains: false,
            require_all_reconstructed: false,
            validate_output: false,
        },
    );
    let edge_pcurve_stale = brep
        .measure_edge_pcurve_deviation(half_edge_data.edge)
        .is_some_and(|report| report.max_deviation > tolerance);
    (matches!(status, ExistingTrimStatus::Stale) || edge_pcurve_stale).then_some(
        BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::StalePcurve,
            reason: BrepRepairAuthorityReason::StalePcurve,
        },
    )
}

fn edge_curve_authority(brep: &BRep, half_edge: HalfEdgeHandle) -> Option<BrepRepairAuthorityFact> {
    let half_edge_data = brep.half_edges.get(half_edge)?;
    let edge = brep.edges.get(half_edge_data.edge)?;
    edge.curve.as_ref()?;
    match edge.canonical {
        CanonicalForm::Canonical3D => Some(BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::AuthoritativeEdgeCurve,
            reason: BrepRepairAuthorityReason::EdgeCanonical3D,
        }),
        CanonicalForm::CanonicalParametric => Some(BrepRepairAuthorityFact {
            kind: BrepRepairAuthorityKind::AuthoritativeTrimEndpoint,
            reason: BrepRepairAuthorityReason::EdgeCanonicalParametric,
        }),
    }
}
