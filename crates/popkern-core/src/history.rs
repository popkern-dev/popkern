//! History tracking for stable topological naming.
//!
//! Records what happened to entities during a single modelling operation
//! (created, modified, deleted). The [`TrackingContext`] is an opt-in handle
//! that operations accept and call back into. When finished, the caller
//! extracts a [`HistoryMap`] summarizing the operation's effects.

use std::collections::HashMap;

use serde::{Deserialize, Serialize};

use crate::naming::{EntityName, OperationId};

// ---------------------------------------------------------------------------
// HistoryMap
// ---------------------------------------------------------------------------

/// Records what happened to entities during one operation.
///
/// * `modified` — for each pre-existing entity that was changed, the list of
///   entities it became (e.g. a face that was split produces two successors).
/// * `generated` — entities that were created from scratch by the operation.
/// * `deleted` — entities that were removed entirely.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct HistoryMap {
    /// The operation that produced this history.
    pub operation: OperationId,
    /// Pre-existing entities that were modified, mapped to their successors.
    pub modified: HashMap<EntityName, Vec<EntityName>>,
    /// Entirely new entities generated by the operation.
    pub generated: Vec<EntityName>,
    /// Entities deleted by the operation.
    pub deleted: Vec<EntityName>,
}

// ---------------------------------------------------------------------------
// TrackingContext
// ---------------------------------------------------------------------------

/// Opt-in tracking context passed to operations.
///
/// Create one before an operation, pass it through, then call [`finish`] to
/// extract the resulting [`HistoryMap`]. Recording is gated on [`enabled`] so
/// that a disabled context has zero overhead.
///
/// [`finish`]: TrackingContext::finish
/// [`enabled`]: TrackingContext::enabled
pub struct TrackingContext {
    /// The operation being tracked.
    pub operation: OperationId,
    /// Whether recording is active. When `false`, all `record_*` calls are
    /// no-ops.
    pub enabled: bool,
    /// Accumulated history (internal; extracted via [`finish`]).
    pub(crate) history: HistoryMap,
    /// The naming scheme the operation mints under
    /// ([`crate::naming::NAMING_SCHEME_VERSION`] unless the document
    /// was recorded under an older one).
    pub naming_scheme: u32,
}

impl TrackingContext {
    /// Create a new enabled tracking context for the given operation.
    pub fn new(operation: OperationId) -> Self {
        Self {
            operation,
            enabled: true,
            history: HistoryMap {
                operation,
                ..Default::default()
            },
            naming_scheme: crate::naming::NAMING_SCHEME_VERSION,
        }
    }

    /// The same context minting under naming scheme `scheme`.
    #[must_use]
    pub fn with_naming_scheme(mut self, scheme: u32) -> Self {
        self.naming_scheme = scheme;
        self
    }

    /// Record that `old` was modified and produced `new`.
    ///
    /// If the same `old` entity is modified multiple times (e.g. successive
    /// splits) the new names accumulate in the successor list.
    pub fn record_modified(&mut self, old: EntityName, new: EntityName) {
        if !self.enabled {
            return;
        }
        self.history.modified.entry(old).or_default().push(new);
    }

    /// Record a newly generated entity.
    pub fn record_generated(&mut self, name: EntityName) {
        if !self.enabled {
            return;
        }
        self.history.generated.push(name);
    }

    /// Record a deleted entity.
    pub fn record_deleted(&mut self, name: EntityName) {
        if !self.enabled {
            return;
        }
        self.history.deleted.push(name);
    }

    /// Consume the context and return the accumulated history.
    pub fn finish(self) -> HistoryMap {
        self.history
    }
}

// ---------------------------------------------------------------------------
// Tests
// ---------------------------------------------------------------------------

#[cfg(test)]
mod tests {
    use super::*;
    use crate::naming::{EntityRole, RoleCategory};

    fn make_name(op: u64, cat: RoleCategory, idx: u32) -> EntityName {
        EntityName {
            operation: OperationId(op),
            role: EntityRole {
                category: cat,
                index: idx,
            },
            ancestors: Vec::new(),
        }
    }

    #[test]
    fn record_and_finish_basic() {
        let op = OperationId(1);
        let mut ctx = TrackingContext::new(op);

        let generated = make_name(1, RoleCategory::Generated, 0);
        ctx.record_generated(generated.clone());

        let old = make_name(0, RoleCategory::Cap, 0);
        let new = make_name(1, RoleCategory::Modified, 0);
        ctx.record_modified(old.clone(), new.clone());

        let del = make_name(0, RoleCategory::Lateral, 0);
        ctx.record_deleted(del.clone());

        let map = ctx.finish();
        assert_eq!(map.operation, op);
        assert_eq!(map.generated.len(), 1);
        assert_eq!(map.generated[0], generated);
        assert_eq!(map.deleted.len(), 1);
        assert_eq!(map.deleted[0], del);
        assert_eq!(map.modified.len(), 1);
        assert_eq!(map.modified[&old], vec![new]);
    }

    #[test]
    fn disabled_context_records_nothing() {
        let op = OperationId(2);
        let mut ctx = TrackingContext::new(op);
        ctx.enabled = false;

        ctx.record_generated(make_name(2, RoleCategory::Generated, 0));
        ctx.record_modified(
            make_name(1, RoleCategory::Cap, 0),
            make_name(2, RoleCategory::Modified, 0),
        );
        ctx.record_deleted(make_name(1, RoleCategory::Lateral, 0));

        let map = ctx.finish();
        assert!(map.generated.is_empty());
        assert!(map.modified.is_empty());
        assert!(map.deleted.is_empty());
    }

    #[test]
    fn modified_same_entity_twice_accumulates() {
        let op = OperationId(3);
        let mut ctx = TrackingContext::new(op);

        let old = make_name(0, RoleCategory::Cap, 0);
        let new_a = make_name(3, RoleCategory::Modified, 0);
        let new_b = make_name(3, RoleCategory::Modified, 1);
        ctx.record_modified(old.clone(), new_a.clone());
        ctx.record_modified(old.clone(), new_b.clone());

        let map = ctx.finish();
        assert_eq!(map.modified[&old].len(), 2);
        assert_eq!(map.modified[&old][0], new_a);
        assert_eq!(map.modified[&old][1], new_b);
    }

    #[test]
    fn finish_returns_correct_operation_id() {
        let op = OperationId(42);
        let ctx = TrackingContext::new(op);
        let map = ctx.finish();
        assert_eq!(map.operation, op);
    }
}
