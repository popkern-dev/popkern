//! Stable topological naming — types and pool.
//!
//! Names are persistent identifiers for topological entities (vertices, edges,
//! faces) that survive feature-tree re-execution. A [`NameId`] is a lightweight
//! index into a [`NamePool`]. Each pool entry stores the [`EntityName`] (the
//! recipe that produced the entity) and an optional [`GeometricCriteria`] hint
//! (used by the resolver when structural names collide).

use std::collections::{HashMap, HashSet};

use serde::{Deserialize, Serialize};

use crate::naming_criteria::GeometricCriteria;

/// Version of the entity-naming scheme this kernel mints: the rule set
/// that decides which [`EntityName`] (operation, role category, index,
/// ancestors) each face, edge, and vertex receives from each operation.
///
/// Documents record the scheme they were written under next to their
/// format version. Changing how any operation mints names — role
/// categories, index order, ancestor recording — is a scheme change:
/// bump this constant and keep the previous scheme's rules reachable
/// (or ship a document migration), because every stored reference is
/// an [`EntityName`] minted under the old rules.
///
/// - **1**: the original rules.
/// - **2** (PK-677): a boolean imports each operand's names into the
///   result pool by value ([`NamePool::import`]), so a tool-side name's
///   ancestor ids are the result pool's. Scheme 1 interned them as-is,
///   leaving ancestor ids that pointed into the tool's pool. A tree
///   keeps the scheme it was recorded under and replays with its rules.
pub const NAMING_SCHEME_VERSION: u32 = 2;

/// The oldest naming scheme this kernel still replays.
pub const OLDEST_NAMING_SCHEME: u32 = 1;

// ---------------------------------------------------------------------------
// Primitive handles
// ---------------------------------------------------------------------------

/// Lightweight opaque handle to a name stored in a [`NamePool`].
///
/// Indexes into `NamePool::names`. Ids are stable within a single pool but
/// must be remapped when pools are merged or compacted.
#[derive(Debug, Clone, Copy, Hash, Eq, PartialEq, Serialize, Deserialize)]
pub struct NameId(pub u32);

/// Identifier for a modelling operation (e.g. a fillet, a boolean, an extrude).
///
/// Assigned by the feature tree; two executions of the same feature use the
/// same `OperationId`.
#[derive(Debug, Clone, Copy, Hash, Eq, PartialEq, Default, Serialize, Deserialize)]
pub struct OperationId(pub u64);

// ---------------------------------------------------------------------------
// Role
// ---------------------------------------------------------------------------

/// Broad category describing how an entity was produced by an operation.
#[derive(Debug, Clone, Copy, Hash, Eq, PartialEq, Serialize, Deserialize)]
pub enum RoleCategory {
    /// An existing entity that was modified in place (e.g. a face that was split).
    Modified,
    /// An entity generated by the operation itself (e.g. the lateral face of an extrude).
    Generated,
    /// A lateral (side) entity, e.g. the cylindrical face of a fillet.
    Lateral,
    /// A cap entity, e.g. the flat end-caps of an extrude.
    Cap,
    /// An entity produced at the intersection of two shapes.
    Intersection,
    /// An entity produced where three or more entities meet.
    Junction,
}

/// Role of an entity within a single operation.
///
/// `category` describes what kind of entity was produced; `index`
/// disambiguates when the same operation produces multiple entities
/// of the same category.
#[derive(Debug, Clone, Copy, Hash, Eq, PartialEq, Serialize, Deserialize)]
pub struct EntityRole {
    /// Broad category.
    pub category: RoleCategory,
    /// Zero-based index within that category for this operation.
    pub index: u32,
}

// ---------------------------------------------------------------------------
// EntityName
// ---------------------------------------------------------------------------

/// The full name of a topological entity.
///
/// Names are *recipes*: they describe how an entity was produced. Two
/// entities with the same name are considered the same entity across
/// re-executions of the feature tree.
///
/// **No `f64` fields** — floating-point values are stored in
/// [`GeometricCriteria`] separately, so that `Hash` and `Eq` are exact.
#[derive(Debug, Clone, Hash, Eq, PartialEq, Serialize, Deserialize)]
pub struct EntityName {
    /// The operation that produced this entity.
    pub operation: OperationId,
    /// The role of this entity within the operation.
    pub role: EntityRole,
    /// The names of ancestor entities that this entity derives from.
    ///
    /// For example, the intersection edge between face A and face B stores
    /// the names of A and B as ancestors.
    pub ancestors: Vec<NameId>,
}

// ---------------------------------------------------------------------------
// OperationLabels
// ---------------------------------------------------------------------------

/// Human-readable labels for operations, keyed by [`OperationId`].
///
/// Useful for debugging and for displaying the feature tree in a UI.
#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct OperationLabels {
    /// Map from operation id to a display label.
    pub labels: HashMap<OperationId, String>,
}

// ---------------------------------------------------------------------------
// NamePool
// ---------------------------------------------------------------------------

/// Central store for all [`EntityName`]s in a model.
///
/// Deduplicates names on insertion — interning the same name twice returns
/// the same [`NameId`]. The reverse index (`index`) is rebuilt from `names`
/// when needed (e.g. after deserialization).
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NamePool {
    /// Names stored in insertion order. `NameId(i)` indexes this vec.
    pub names: Vec<EntityName>,
    /// Optional geometric criteria stored parallel to `names`.
    ///
    /// `criteria[i]` corresponds to `names[i]`. May be `None` when no
    /// geometric hint is available or relevant.
    pub criteria: Vec<Option<GeometricCriteria>>,
    /// Provenance beside each name (PK-633): the names (as VALUES, so
    /// they stay comparable across pools) of the entities this one was
    /// cut, trimmed or carried from, transitively. NOT part of a name's
    /// identity — a stable name never changes because lineage was
    /// recorded — but what lets a label or spelled name bound earlier
    /// find its entity after a later operation. Parallel to `names`
    /// (shorter in documents written before it existed: missing entries
    /// are empty). See [`NamePool::add_lineage`].
    #[serde(default)]
    pub lineage: Vec<Vec<EntityName>>,
    /// Reverse index: name → id. Rebuilt after deserialization.
    #[serde(skip)]
    index: HashMap<EntityName, NameId>,
}

impl Default for NamePool {
    fn default() -> Self {
        Self::new()
    }
}

impl NamePool {
    /// Create an empty pool.
    pub fn new() -> Self {
        Self {
            names: Vec::new(),
            criteria: Vec::new(),
            lineage: Vec::new(),
            index: HashMap::new(),
        }
    }

    /// Intern a name, returning the existing [`NameId`] if already present.
    ///
    /// `criteria` is stored alongside the name and replaces the existing
    /// criteria if the name was already in the pool.
    pub fn intern(&mut self, name: EntityName, criteria: Option<GeometricCriteria>) -> NameId {
        if let Some(&id) = self.index.get(&name) {
            // Update criteria even if the name is already present.
            self.criteria[id.0 as usize] = criteria;
            return id;
        }
        let id = NameId(self.names.len() as u32);
        self.index.insert(name.clone(), id);
        self.names.push(name);
        self.criteria.push(criteria);
        id
    }

    /// Look up a name by id.
    pub fn get(&self, id: NameId) -> Option<&EntityName> {
        self.names.get(id.0 as usize)
    }

    /// Look up the geometric criteria for a name id.
    pub fn get_criteria(&self, id: NameId) -> Option<&GeometricCriteria> {
        self.criteria.get(id.0 as usize)?.as_ref()
    }

    /// Find the id for an existing name without inserting.
    pub fn find(&self, name: &EntityName) -> Option<NameId> {
        self.index.get(name).copied()
    }

    /// Rebuild the reverse index from `names`.
    ///
    /// Call after deserialization (the index is not serialized).
    pub fn rebuild_index(&mut self) {
        self.index.clear();
        for (i, name) in self.names.iter().enumerate() {
            self.index.insert(name.clone(), NameId(i as u32));
        }
    }

    /// Number of names in the pool.
    pub fn len(&self) -> usize {
        self.names.len()
    }

    /// True if the pool is empty.
    pub fn is_empty(&self) -> bool {
        self.names.is_empty()
    }

    /// Import all names from `other` into `self`.
    ///
    /// Returns a map from `other`'s [`NameId`]s to their new ids in `self`.
    /// Ancestor references inside imported names are also remapped so they
    /// point into `self`.
    ///
    /// Names that already exist in `self` are not duplicated; they receive
    /// the existing id in the returned map.
    pub fn merge(&mut self, other: &NamePool) -> HashMap<NameId, NameId> {
        let mut remap: HashMap<NameId, NameId> = HashMap::new();

        for (i, name) in other.names.iter().enumerate() {
            let old_id = NameId(i as u32);
            // Remap ancestors using what we've mapped so far.
            let new_ancestors: Vec<NameId> = name
                .ancestors
                .iter()
                .map(|a| remap.get(a).copied().unwrap_or(*a))
                .collect();
            let remapped = EntityName {
                operation: name.operation,
                role: name.role,
                ancestors: new_ancestors,
            };
            let criteria = other.criteria[i].clone();
            let new_id = self.intern(remapped, criteria);
            self.add_lineage(new_id, other.lineage(old_id).iter().cloned());
            remap.insert(old_id, new_id);
        }
        remap
    }

    /// Remove unreferenced names and return a remapping of surviving ids.
    ///
    /// `referenced` is the set of ids that must be kept. Ancestors of
    /// referenced names are **not** automatically preserved — call sites
    /// should include transitive ancestors in `referenced` if needed.
    ///
    /// Returns a map from old [`NameId`] to new [`NameId`] for all surviving
    /// names. Dead names have no entry in the map.
    pub fn compact(&mut self, referenced: &HashSet<NameId>) -> HashMap<NameId, NameId> {
        let mut remap: HashMap<NameId, NameId> = HashMap::new();
        let mut new_names: Vec<EntityName> = Vec::new();
        let mut new_criteria: Vec<Option<GeometricCriteria>> = Vec::new();
        let mut new_lineage: Vec<Vec<EntityName>> = Vec::new();

        for (i, name) in self.names.iter().enumerate() {
            let old_id = NameId(i as u32);
            if !referenced.contains(&old_id) {
                continue;
            }
            let new_id = NameId(new_names.len() as u32);
            remap.insert(old_id, new_id);
            new_names.push(name.clone());
            new_criteria.push(self.criteria[i].clone());
            new_lineage.push(self.lineage.get(i).cloned().unwrap_or_default());
        }

        // Remap ancestor references inside surviving names.
        for name in &mut new_names {
            for ancestor in &mut name.ancestors {
                if let Some(&mapped) = remap.get(ancestor) {
                    *ancestor = mapped;
                }
            }
        }

        self.names = new_names;
        self.criteria = new_criteria;
        self.lineage = new_lineage;
        self.rebuild_index();
        remap
    }
}

