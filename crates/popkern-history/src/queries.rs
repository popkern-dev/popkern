//! Dependency queries and impact analysis for the parametric feature tree.
//!
//! Provides graph-traversal queries that answer questions such as:
//! *"which features depend on this one?"*, *"what are this feature's direct
//! parents?"*, and *"if I change this feature, what will need to rebuild?"*.

use std::collections::HashSet;

use popkern_core::naming::EntityName;

use crate::FeatureTree;
use crate::error::FeatureResult;
use crate::node::FeatureId;
use crate::timeline::feature_entity_names;

// ---------------------------------------------------------------------------
// Public types
// ---------------------------------------------------------------------------

/// Impact analysis result for a single feature.
///
/// Describes how changing the feature would affect the rest of the tree.
#[derive(Debug)]
pub struct ImpactReport {
    /// Every feature that will need to be rebuilt (all downstream dependents,
    /// in timeline order).
    pub will_rebuild: Vec<FeatureId>,
    /// Features whose entity-name references point into the changed feature's
    /// output, paired with the specific names that are at risk.
    pub at_risk: Vec<(FeatureId, Vec<EntityName>)>,
}

// ---------------------------------------------------------------------------
// FeatureTree impl
// ---------------------------------------------------------------------------

impl FeatureTree {
    /// Return all features that transitively depend on `id`, in timeline order.
    ///
    /// Uses a single-pass walk over the timeline — O(n) rather than O(n^2).
    /// The result does **not** include `id` itself.
    pub fn dependents(&self, id: FeatureId) -> Vec<FeatureId> {
        let mut visited = HashSet::new();
        visited.insert(id);
        let mut result = Vec::new();

        for &fid in &self.timeline {
            if fid == id {
                continue;
            }
            if let Some(node) = self.features.get(fid)
                && node.depends_on.iter().any(|dep| visited.contains(dep))
            {
                visited.insert(fid);
                result.push(fid);
            }
        }
        result
    }

    /// Return the direct dependencies of `id` (the features it depends on).
    ///
    /// Returns an empty [`Vec`] if the feature does not exist.
    pub fn dependencies(&self, id: FeatureId) -> Vec<FeatureId> {
        self.features
            .get(id)
            .map(|node| node.depends_on.clone())
            .unwrap_or_default()
    }

    /// Analyse the impact of modifying feature `id`.
    ///
    /// Walks the dependency graph to produce:
    /// - `will_rebuild`: every transitively dependent feature (in timeline
    ///   order) that would need re-evaluation.
    /// - `at_risk`: dependents whose [`EntityName`] references point into `id`'s
    ///   generated output — these are the features most likely to break if the
    ///   topology produced by `id` changes shape or count.
    ///
    /// If `id` has no cached successful result (`last_result`) the `at_risk`
    /// list will be empty (nothing to compare against).
    pub fn impact_analysis(&self, id: FeatureId) -> ImpactReport {
        let will_rebuild = self.dependents(id);

        let mut at_risk: Vec<(FeatureId, Vec<EntityName>)> = Vec::new();

        if let Some(node) = self.features.get(id)
            && let Some(FeatureResult::Success { history }) = &node.last_result
        {
            // Names generated by this feature's last successful evaluation.
            let generated_names: HashSet<&EntityName> = history.generated.iter().collect();

            // For each downstream dependent, check whether any of its
            // entity-name references match a name produced by `id`.
            // We match on `operation_id` rather than strict equality because
            // the name's index might shift after a rebuild.
            for &dep_id in &will_rebuild {
                if let Some(dep_node) = self.features.get(dep_id) {
                    let refs = feature_entity_names(&dep_node.feature);
                    let at_risk_refs: Vec<EntityName> = refs
                        .into_iter()
                        .filter(|name| name.operation == node.operation_id)
                        .filter(|name| generated_names.contains(name))
                        .cloned()
                        .collect();
                    if !at_risk_refs.is_empty() {
                        at_risk.push((dep_id, at_risk_refs));
                    }
                }
            }
        }

        ImpactReport {
            will_rebuild,
            at_risk,
        }
    }
}

