macro_rules! matrix_row {
    (
        $case_id:literal, $fixture_tier:expr, [$($axis:expr),* $(,)?],
        $terminal:expr, $candidate_family:literal, $feasibility:literal,
        $geometry_required:expr, $geometry:expr,
        $validity_required:expr, $validity:expr,
        $dependency_required:expr, $dependency:expr,
        $downstream_required:expr, $downstream:expr,
        $reason:literal, $unknown:expr, $task:expr $(,)?
    ) => {
        DiagnosticMatrixRow {
            case_id: $case_id,
            fixture_tier: $fixture_tier,
            covered_axes: &[$($axis),*],
            terminal: $terminal,
            candidate_family: $candidate_family,
            feasibility: $feasibility,
            geometry_feasibility_required: $geometry_required,
            geometry_feasibility: $geometry,
            validity_repair_required: $validity_required,
            validity_repair: $validity,
            operation_dependency_required: $dependency_required,
            operation_dependency: $dependency,
            downstream_readiness_required: $downstream_required,
            downstream_readiness: $downstream,
            expected_reason: $reason,
            unknown_facet: $unknown,
            closure_task: $task,
        }
    };
}

