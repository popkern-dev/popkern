//! Wavefront OBJ format export for [`TriMesh`].

use std::io::Write;

use crate::MeshError;
use crate::mesh::TriMesh;

/// Write a [`TriMesh`] to the Wavefront OBJ format.
///
/// The output structure is:
/// - A comment header identifying the generator.
/// - One `v x y z` line per vertex (all face meshes in order).
/// - One `vn nx ny nz` line per vertex normal.
/// - One `vt u v` line per UV coordinate.
/// - For each face mesh, a `g face_N` group line followed by `f` lines
///   referencing 1-based vertex/UV/normal indices.
///
/// Indices in OBJ format are 1-based. Each face mesh is assigned a contiguous
/// block of global vertex indices, offset by the cumulative vertex count of all
/// preceding face meshes.
pub(crate) fn write_obj<W: Write>(mesh: &TriMesh, writer: &mut W) -> Result<(), MeshError> {
    writeln!(writer, "# Generated by popkern")?;

    // Write all vertices.
    for v in &mesh.vertices {
        writeln!(
            writer,
            "v {} {} {}",
            v.position.x, v.position.y, v.position.z
        )?;
    }

    // Write all normals.
    for v in &mesh.vertices {
        writeln!(writer, "vn {} {} {}", v.normal.x, v.normal.y, v.normal.z)?;
    }

    // Write all UV coordinates.
    for v in &mesh.vertices {
        writeln!(writer, "vt {} {}", v.uv.0, v.uv.1)?;
    }

    // Write each face mesh as a named group.
    let mut vertex_offset: usize = 0;
    for (face_idx, face_mesh) in mesh.face_meshes.iter().enumerate() {
        writeln!(writer, "g face_{}", face_idx)?;
        for tri in &face_mesh.triangles {
            // OBJ indices are 1-based; apply the per-face vertex offset.
            let a = tri[0] + vertex_offset + 1;
            let b = tri[1] + vertex_offset + 1;
            let c = tri[2] + vertex_offset + 1;
            writeln!(writer, "f {a}/{a}/{a} {b}/{b}/{b} {c}/{c}/{c}")?;
        }
        vertex_offset += face_mesh.vertices.len();
    }

    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::{TessellationOptions, tessellate};
    use popkern_core::tolerance::Tolerance;
    use popkern_core::topology::BRep;
    use std::io::Write;

    fn make_cube_mesh() -> TriMesh {
        let cube = BRep::unit_cube(Tolerance::default()).unwrap();
        tessellate(&cube, &TessellationOptions::default()).unwrap()
    }

    #[test]
    fn obj_vertex_count_matches_mesh() {
        let mesh = make_cube_mesh();
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        let v_count = text.lines().filter(|l| l.starts_with("v ")).count();
        assert_eq!(v_count, mesh.vertices.len());
    }

    #[test]
    fn obj_normal_count_matches_vertex_count() {
        let mesh = make_cube_mesh();
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        let vn_count = text.lines().filter(|l| l.starts_with("vn ")).count();
        assert_eq!(vn_count, mesh.vertices.len());
    }

    #[test]
    fn obj_uv_count_matches_vertex_count() {
        let mesh = make_cube_mesh();
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        let vt_count = text.lines().filter(|l| l.starts_with("vt ")).count();
        assert_eq!(vt_count, mesh.vertices.len());
    }

    #[test]
    fn obj_face_groups_match_brep_face_count() {
        let mesh = make_cube_mesh();
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        let group_count = text.lines().filter(|l| l.starts_with("g face_")).count();
        // Unit cube has 6 faces.
        assert_eq!(group_count, mesh.face_meshes.len());
        assert_eq!(group_count, 6);
    }

    #[test]
    fn obj_all_face_indices_are_one_based() {
        let mesh = make_cube_mesh();
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        for line in text.lines().filter(|l| l.starts_with('f')) {
            // Each face token is "v/vt/vn" — all must be >= 1.
            for token in line.split_whitespace().skip(1) {
                for part in token.split('/') {
                    let idx: usize = part.parse().unwrap();
                    assert!(idx >= 1, "OBJ index must be 1-based, got {idx}");
                }
            }
        }
    }

    #[test]
    fn obj_export_to_temp_file() {
        let mesh = make_cube_mesh();
        let mut tmp = tempfile::NamedTempFile::new().unwrap();
        write_obj(&mesh, tmp.as_file_mut()).unwrap();
        let path = tmp.path().to_owned();
        assert!(path.exists());
        let content = std::fs::read_to_string(&path).unwrap();
        assert!(content.starts_with("# Generated by popkern"));
        assert!(content.contains("g face_0"));
    }

    #[test]
    fn obj_no_zero_indices_in_face_lines() {
        let mesh = make_cube_mesh();
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        for line in text.lines().filter(|l| l.starts_with('f')) {
            // Confirm no "/0" appears (which would be a zero index).
            assert!(!line.contains("/0"), "Found zero index in: {line}");
            // Confirm line doesn't start with "f 0" either.
            assert!(
                !line.starts_with("f 0"),
                "Found zero-start index in: {line}"
            );
        }
    }
}
