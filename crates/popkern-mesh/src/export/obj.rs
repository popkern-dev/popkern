    #[test]
    fn obj_multi_face_indices_offset_correctly() {
        use crate::mesh::{FaceMesh, MeshVertex};
        use popkern_core::geometry::{Point3, Vec3};
        use popkern_core::topology::FaceHandle;

        let make_vert = |x, y, z| MeshVertex {
            position: Point3::new(x, y, z),
            normal: Vec3::new(0.0, 0.0, 1.0),
            uv: (0.0, 0.0),
        };

        let fm1 = FaceMesh {
            face: FaceHandle::default(),
            vertices: vec![
                make_vert(0.0, 0.0, 0.0),
                make_vert(1.0, 0.0, 0.0),
                make_vert(0.0, 1.0, 0.0),
            ],
            triangles: vec![[0, 1, 2]],
        };
        let fm2 = FaceMesh {
            face: FaceHandle::default(),
            vertices: vec![
                make_vert(2.0, 0.0, 0.0),
                make_vert(3.0, 0.0, 0.0),
                make_vert(2.0, 1.0, 0.0),
            ],
            triangles: vec![[0, 1, 2]],
        };
        let mesh = TriMesh::from_face_meshes(vec![fm1, fm2]);
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        let face_lines: Vec<&str> = text.lines().filter(|l| l.starts_with("f ")).collect();
        // First face group: indices 1,2,3
        assert_eq!(face_lines[0], "f 1/1/1 2/2/2 3/3/3");
        // Second face group: offset by 3 -> indices 4,5,6
        assert_eq!(face_lines[1], "f 4/4/4 5/5/5 6/6/6");
    }

    #[test]
    fn obj_face_indices_never_exceed_vertex_count() {
        let mesh = make_cube_mesh();
        let mut buf = Vec::new();
        write_obj(&mesh, &mut buf).unwrap();
        let text = String::from_utf8(buf).unwrap();
        let num_verts = mesh.vertices.len();
        for line in text.lines().filter(|l| l.starts_with('f')) {
            for token in line.split_whitespace().skip(1) {
                for part in token.split('/') {
                    let idx: usize = part.parse().unwrap();
                    assert!(
                        idx <= num_verts,
                        "OBJ index {idx} exceeds vertex count {num_verts}"
                    );
                }
            }
        }
    }

