//! PK-996: chamfers at mixed corners, fills first.
//!
//! A concave (fill) chamfer and a convex (cut) chamfer ending at one
//! vertex have no order-independent corner (cut bounded by the fill,
//! fill bounded by the cut, or each by the other on its own side, are
//! three valid solids). One chamfer operation builds the fills first
//! and the cuts against them, whatever order the edges are given in,
//! and names the result as one feature. Volumes are exact closed forms;
//! the two-stage construction also matches OpenCASCADE applying the
//! same two stages in its own kernel (1e-10, probe matrix).

#[path = "support/chamfer_fixtures.rs"]
#[allow(dead_code)] // not every fixture is used here
mod chamfer_fixtures;
#[path = "support/mesh_gauges.rs"]
#[allow(dead_code)] // the welded-mesh gauge is not used here
mod mesh_gauges;

use chamfer_fixtures::*;
use popkern_blend::{ChamferKind, ChamferOptions, ChamferSpec, chamfer_edges};
use popkern_core::tolerance::Tolerance;

/// A concave (fill) chamfer and convex (cut) chamfers ending at the same
/// vertex: the fill is built first and the cuts end against it, in one
/// operation, whatever order the edges are given in.
#[test]
fn mixed_corner_fills_first() {
    let l = l_prism();
    let inside = (p(1.0, 1.0, 0.0), p(1.0, 1.0, 0.5));
    let top_x = (p(2.0, 1.0, 0.5), p(1.0, 1.0, 0.5));
    let top_y = (p(1.0, 1.0, 0.5), p(1.0, 2.0, 0.5));
    let one = chamfer(&l, &[inside, top_x], D).expect("inside + one top edge serves");
    assert_exact(
        "L inside + top",
        &one,
        1.5 + fill(0.5) - cut_against_fill(1.0),
    );
    let reversed = chamfer(&l, &[top_x, inside], D).expect("reversed order serves");
    assert_exact(
        "L top + inside",
        &reversed,
        1.5 + fill(0.5) - cut_against_fill(1.0),
    );
    assert_eq!(one.faces.len(), reversed.faces.len(), "order independent");
    let both = chamfer(&l, &[top_y, inside, top_x], D).expect("inside + both tops serves");
    assert_exact(
        "L inside + both tops",
        &both,
        1.5 + fill(0.5) - 2.0 * cut_against_fill(1.0),
    );

    let pocket = pocket_block();
    let wall = (p(-0.5, 0.5, 0.5), p(-0.5, 0.5, 1.0));
    let rim_y = (p(-0.5, 0.5, 1.0), p(0.5, 0.5, 1.0));
    let rim_x = (p(-0.5, -0.5, 1.0), p(-0.5, 0.5, 1.0));
    let out = chamfer(&pocket, &[wall, rim_y], D).expect("pocket wall + rim serves");
    assert_exact(
        "pocket wall + rim",
        &out,
        3.5 + fill(0.5) - cut_against_fill(1.0),
    );
    let out = chamfer(&pocket, &[rim_x, wall, rim_y], D).expect("pocket wall + rims serves");
    assert_exact(
        "pocket wall + rims",
        &out,
        3.5 + fill(0.5) - 2.0 * cut_against_fill(1.0),
    );
}

/// A two-distance cut at a mixed corner: its reference face is carried
/// onto the filled body. With `a` on the top and `b` down the wall, the
/// wedge is `ab/2` over length 1, and the fill's plane keeps
/// `∫∫ (d + u) dA = d·ab/2 + a²b/6` of it.
#[test]
fn mixed_corner_two_distance_cut() {
    let l = l_prism();
    let top = l
        .faces
        .keys()
        .find(|&f| {
            l.face_outer_loop_positions(f)
                .iter()
                .all(|q| (q.z - 0.5).abs() < 1e-12)
        })
        .expect("top face");
    let (a, b) = (0.1, 0.2);
    let specs = [
        ChamferSpec {
            edge: edge(&l, p(1.0, 1.0, 0.0), p(1.0, 1.0, 0.5)),
            kind: ChamferKind::Equal(D),
        },
        ChamferSpec {
            edge: edge(&l, p(2.0, 1.0, 0.5), p(1.0, 1.0, 0.5)),
            kind: ChamferKind::TwoDistance {
                face_1: top,
                dist_1: a,
                dist_2: b,
            },
        },
    ];
    let out = chamfer_edges(
        &l,
        &specs,
        &ChamferOptions::default(),
        Tolerance::default(),
        None,
    )
    .expect("serves")
    .brep;
    let removed = a * b / 2.0 - (D * a * b / 2.0 + a * a * b / 6.0);
    assert_exact(
        "L inside + two-distance top",
        &out,
        1.5 + fill(0.5) - removed,
    );
}

/// The two stages are one feature, named against the original input:
/// roles are unique and the stage-1 fill face is Generated by it.
#[test]
fn mixed_corner_names_one_feature() {
    use popkern_core::history::TrackingContext;
    use popkern_core::naming::OperationId;
    let l = l_prism();
    let specs: Vec<ChamferSpec> = [
        (p(1.0, 1.0, 0.0), p(1.0, 1.0, 0.5)),
        (p(2.0, 1.0, 0.5), p(1.0, 1.0, 0.5)),
    ]
    .iter()
    .map(|&(a, b)| ChamferSpec {
        edge: edge(&l, a, b),
        kind: ChamferKind::Equal(D),
    })
    .collect();
    let op = OperationId(7);
    let mut ctx = TrackingContext::new(op);
    let out = chamfer_edges(
        &l,
        &specs,
        &ChamferOptions::default(),
        Tolerance::default(),
        Some(&mut ctx),
    )
    .expect("serves")
    .brep;
    use popkern_core::geometry::surface::SurfaceGeometry;
    use popkern_core::naming::RoleCategory;
    let mut roles = std::collections::HashSet::new();
    let mut generated = 0;
    let mut fill = None;
    for face in out.faces.values() {
        let name = face
            .name
            .and_then(|id| out.name_pool.get(id))
            .expect("every face named");
        if name.operation == op {
            assert!(roles.insert(name.role), "duplicate role {:?}", name.role);
            generated += usize::from(name.role.category == RoleCategory::Generated);
        }
        // The stage-1 fill face: the vertical plane x + y = 2.1.
        if let Some(SurfaceGeometry::Plane { normal, .. }) =
            face.surface.as_ref().map(|s| &s.geometry)
            && (normal.x.abs() - normal.y.abs()).abs() < 1e-9
            && normal.x.abs() > 0.5
            && normal.z.abs() < 1e-9
        {
            fill = Some((name.operation, name.role.category));
        }
    }
    // Named against the ORIGINAL input, the fill is new to the feature
    // (against the intermediate body it would read Modified, and only
    // the second stage's faces would count as Generated).
    assert_eq!(fill, Some((op, RoleCategory::Generated)), "fill face");
    // Each stage generates its bevel and, as every chamfer does today,
    // re-mints one trimmed support (PK-1000): 2 per stage.
    assert_eq!(
        generated, 4,
        "two stages' generated faces under one feature"
    );
}

/// A mixed corner the fills-first construction cannot build (the fill
/// overruns a 0.05 wall) declines naming the corner, hands the input
/// back, and points at the other order.
#[test]
fn mixed_corner_decline_names_the_corner() {
    let short = prism(
        &[
            (0.0, 0.0),
            (1.05, 0.0),
            (1.05, 1.0),
            (1.0, 1.0),
            (1.0, 2.0),
            (0.0, 2.0),
        ],
        0.0,
        0.5,
    );
    let err = chamfer(
        &short,
        &[
            (p(1.0, 1.0, 0.0), p(1.0, 1.0, 0.5)),
            (p(1.05, 1.0, 0.5), p(1.0, 1.0, 0.5)),
        ],
        D,
    )
    .expect_err("declines");
    let popkern_blend::BlendError::PartialFailure {
        failures,
        partial_result,
        ..
    } = err
    else {
        panic!("expected a per-edge decline, got {err:?}");
    };
    assert_eq!(
        partial_result.faces.len(),
        short.faces.len(),
        "input handed back"
    );
    assert!(!failures.is_empty());
    for (_, failure) in &failures {
        let popkern_blend::BlendFailure::VertexBlendFailed {
            reason, location, ..
        } = failure
        else {
            panic!("expected the corner to be named, got {failure:?}");
        };
        assert!(reason.starts_with("mixed chamfer corner"), "{reason}");
        assert!(location.is_some_and(|q| q.distance_to(&p(1.0, 1.0, 0.5)) < 1e-9));
        let hint = failure.remediation_hint();
        assert!(hint.rationale.contains("other order"), "{}", hint.rationale);
    }
}
