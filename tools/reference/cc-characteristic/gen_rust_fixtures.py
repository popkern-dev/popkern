"""Emit Rust fixture constants for the CC characteristic ring.

Prints, for each valence in VALENCES, the subdominant eigenvalue, the
three picked 4x4 complex B-spline grids of the level-1 characteristic
ring (Stam q1/q2/q3 order, Fig-1 row-major storage: entry [r][c] with
r = v-row 0..3, c = u-column 0..3), and the PR08 normalization value
f(1,1,0) computed from the q2 grid corner.

The values are RAW (unnormalized) — deterministic because the ring
seed is closed form: EV -> 0, edge vertex of spoke j ->
(4λ-1)·e^{2πi(j-1)/n}, face vertex -> (1+e^{2πi/n})·e^{2πi(j-1)/n},
outer 7 by the (S12 - λI)x = -S11·ring solve, one Ā subdivision,
Stam picking. See README.md and the recovery plan WP1.
"""

import numpy as np
from verify_stam import char_net, build_A_Abar, picks

VALENCES = [3, 5, 6, 7, 8]


def fmt(x: float) -> str:
    return f"{x:.17e}"


def main() -> None:
    print("// Generated by tools/reference/cc-characteristic/gen_rust_fixtures.py")
    print("// (raw closed-form-seed values; see that directory's README).")
    for n in VALENCES:
        lam, cnet = char_net(n)
        _, abar = build_A_Abar(n)
        refined = abar @ cnet
        p = picks(n)
        b = [1 / 6, 2 / 3, 1 / 6]
        g2 = np.array([refined[i - 1] for i in p[2]]).reshape(4, 4)
        # f(1,1,0): B-spline value at the outer corner of the q2 grid,
        # 3x3 CPs nearest grid corner (3,3), tensored with [1/6,2/3,1/6].
        corner = g2[1:4, 1:4]
        f110 = 0.0 + 0.0j
        for r in range(3):
            for c in range(3):
                f110 += b[r] * b[c] * corner[r][c]
        print(f"// ---- n = {n} ----")
        print(f"pub const CC_RING_LAMBDA_N{n}: f64 = {fmt(lam)};")
        print(
            f"pub const CC_RING_F110_N{n}: [f64; 2] = [{fmt(f110.real)}, {fmt(f110.imag)}];"
        )
        for k in (1, 2, 3):
            grid = np.array([refined[i - 1] for i in p[k]]).reshape(4, 4)
            print(
                f"pub const CC_RING_GRID_Q{k}_N{n}: [[[f64; 2]; 4]; 4] = ["
            )
            for r in range(4):
                row = ", ".join(
                    f"[{fmt(grid[r][c].real)}, {fmt(grid[r][c].imag)}]"
                    for c in range(4)
                )
                print(f"    [{row}],")
            print("];")


if __name__ == "__main__":
    main()
